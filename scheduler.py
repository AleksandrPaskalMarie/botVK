import schedule
import time
from generator import generate_joke
from publisher import post_to_vk

def job():
    """
    Это задача, которая будет выполняться по расписанию.
    Она берёт шутку из генератора и отправляет её в публикатор.
    """
    print("[⏳] Генерирую шутку...")
    joke = generate_joke()
    print("[📤] Отправляю в VK...")
    post_to_vk(joke)
    print("[✅] Задача выполнена!")

# --- НАСТРАИВАЕМ РАСПИСАНИЕ ---
# Запуск каждый день в 10:00
schedule.every().day.at("10:00").do(job)

# Для теста — можно раскомментировать и запустить прямо сейчас (но тогда закомментируй строчку выше)
# schedule.every(10).seconds.do(job)

print("[⏳] Бот запущен и ждёт расписания...")
print("[📅] Ближайший запуск: каждый день в 10:00")

# --- БЕСКОНЕЧНЫЙ ЦИКЛ, КОТОРЫЙ ЖДЁТ КОМАНД ---
while True:
    schedule.run_pending()  # Проверяет, не пора ли выполнить задачу
    time.sleep(60)         # Спит 60 секунд, чтобы не нагружать процессор